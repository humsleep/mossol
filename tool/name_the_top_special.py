def main() -> int:
    events = story_io.load("events_special.json")
    index = story_io.by_id(events)
    missing, changed = [], 0
    for eid, pairs in SPECIAL.items():
        ev = index.get(eid)
        if ev is None:
            missing.append(f"{eid}: 이벤트 없음")
            continue
        hits = _apply(ev, pairs)
        for old, n in hits.items():
            if n == 0:
                missing.append(f'{eid}: 못 찾음 "{old}"')
        changed += sum(hits.values())
    if missing:
        print("멈춤 — 바꿀 대상을 못 찾았다(파일은 그대로 둔다):", file=sys.stderr)
        for m in missing:
            print("  " + m, file=sys.stderr)
        return 1
    story_io.save("events_special.json", events)
    print(f"위기·히든 {len(SPECIAL)}개 · {changed}곳을 {{top}} 으로 고쳤다.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
