def _already(cur, new):
    """이 줄에 이미 표가 적용됐는가. S3 뒤에 S1 이 말머리를 손댄 경우까지 본다."""
    if cur == new:
        return True
    bare = strip_lead(new) if new.startswith(LEAD) else new
    return cur == bare or (cur.endswith(bare) and len(cur) - len(bare) <= 4)


class Store:
    def __init__(self):
        self.files = {f: json.loads((STORY / f).read_text(encoding='utf-8')) for f in EVENT_FILES}
        self.endings = json.loads((STORY / 'endings.json').read_text(encoding='utf-8'))
        self.by_id = {}
        self.order = []
        for f, evs in self.files.items():
            for ev in evs:
                self.by_id[ev['id']] = ev
                self.order.append(ev)
        self.changed = 0
        self.problems = []

    def line_at(self, ev, path):
        return _line_at(ev, path)

    def edit(self, ev_id, path, old, new, who=None, tag=''):
        ev = self.by_id.get(ev_id)
        if ev is None:
            self.problems.append(f'{ev_id}: 이벤트 없음 ({tag})')
            return
        for name, arr, put in iter_arrays(ev):
            if not path.startswith(name + '['):
                continue
            i = int(path[len(name) + 1:-1])
            if i >= len(arr):
                break
            cur = arr[i]
            if old is not None and line_text(cur) != old:
                if _already(line_text(cur), new):
                    return  # 이미 적용됨(뒤이어 S1 이 말머리를 손댄 것 포함) — 멱등
                self.problems.append(
                    f'{ev_id}.{path}: 원문이 다르다 ({tag})\n    있음: {line_text(cur)!r}\n    표  : {old!r}')
                return
            if line_text(cur) == new and (who is None or line_who(cur) == who):
                return
            new_arr = list(arr)
            new_arr[i] = set_line(cur, text=new, who=who)
            put(new_arr)
            self.changed += 1
            return
        self.problems.append(f'{ev_id}.{path}: 경로 없음 ({tag})')

    def write(self):
        for f, evs in self.files.items():
            (STORY / f).write_text(json.dumps(evs, ensure_ascii=False, indent=1), encoding='utf-8')
        (STORY / 'endings.json').write_text(
            json.dumps(self.endings, ensure_ascii=False, indent=1), encoding='utf-8')


def apply_tables(st):
    for ev_id, path, old, new in FIX_SMALL:
        st.edit(ev_id, path, old, new, tag='S0')
    for e in st.endings:
        for eid, old, new in FIX_ENDINGS:
            if e['id'] == eid:
                if e.get('epilogue') == old:
                    e['epilogue'] = new
                    st.changed += 1
                elif e.get('epilogue') != new:
                    st.problems.append(f'엔딩 {eid}: 원문이 다르다\n    있음: {e.get("epilogue")!r}')
    seen = set()
    for ev_id, path, old, new in FIX_SIGNATURE:
        if old == new or (ev_id, path) in seen:
            continue            # 손대지 않기로 한 줄, 또는 표에 두 번 적힌 줄
        seen.add((ev_id, path))
        st.edit(ev_id, path, old, new, tag='S3')
    for ev_id, path, old, new, who in FIX_ANON:
        st.edit(ev_id, path, old, new, who=who, tag='S2')


def apply_dots(st):
    """S1 — 경로당 1회 규칙으로 고른 뒤, 캐릭터 상한을 넘는 만큼 더 덜어낸다."""
    them_total = {}
    for ev in st.order:
        for name, arr, _ in iter_arrays(ev):
            for l in arr:
                if line_who(l) == 'them':
                    k = speaker_of(ev, l)
                    them_total[k] = them_total.get(k, 0) + 1

    kept, drop = [], []
    for idx, ev in enumerate(st.order):
        k, d = plan_dots(ev)
        for path in sorted(d):
            drop.append((ev, path))
        for path in sorted(k):
            _n, arr, i = st.line_at(ev, path)
            if arr is None:
                continue
            kept.append((idx, ev, path, speaker_of(ev, arr[i]), line_text(arr[i]).strip() == LEAD))

    # 캐릭터 상한
    by_who = {}
    for row in kept:
        by_who.setdefault(row[3], []).append(row)
    for who_key, rows in by_who.items():
        cap = round(them_total.get(who_key, 0) * DOT_CAP.get(who_key, DOT_CAP_DEFAULT))
        if len(rows) <= cap:
            continue

        def rank(r):
            # 남길 순서: 보호 줄 → 침묵 한 칸("…" 뿐인 줄) → 본문 lines → reply →
            # critReply → failReply. 같으면 앞 이벤트부터.
            idx, ev, path, _w, alone = r
            if (ev['id'], path) in PROTECTED:
                return (0, 0, 0, 0)
            kind = 0 if path.startswith('L[') else (
                1 if '.reply[' in path else (2 if '.critReply[' in path else 3))
            _n, arr, i = _line_at(ev, path)
            short = arr is not None and len(strip_lead(line_text(arr[i]))) <= 8
            return (1, 0 if alone else 1, 0 if short else 1, kind, idx)
        rows.sort(key=rank)
        for row in rows[cap:]:
            drop.append((row[1], row[2]))

    nth = {}
    for ev, path in drop:
        name, arr, i = st.line_at(ev, path)
        if arr is None:
            continue
        cur = arr[i]
        if not line_text(cur).startswith(LEAD):
            continue
        who_key = speaker_of(ev, cur)
        n = nth.get(who_key, 0)
        nth[who_key] = n + 1
        st.edit(ev['id'], path, line_text(cur), rewrite_dot(line_text(cur), who_key, n), tag='S1')


def main():
    dry = '--dry-run' in sys.argv
    st = Store()
    apply_tables(st)
    apply_dots(st)
    if st.problems:
        print(f'멈춤 — 표와 원문이 맞지 않는 곳 {len(st.problems)}곳:\n')
        for p in st.problems:
            print(' -', p)
        return 1
    print(f'{st.changed}줄 고침' + (' (--dry-run: 파일은 안 썼다)' if dry else ''))
    if not dry:
        st.write()
    return 0


if __name__ == '__main__':
    sys.exit(main())
