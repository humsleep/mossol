def speaker_of(ev, l):
    return line_name(l) or ev.get('character') or '(anon)'


def strip_lead(text):
    return text[len(LEAD):].lstrip()


# 이 글자로 시작하는 줄에는 앞말을 붙이지 않는다 — 감탄사가 겹치거나 문장이 깨진다.
NO_PREFIX_HEAD = ('아', '오', '어', '야', '음', '응', '네', '예', '와', '헐', '그', '근데', '잠깐',
                  'ㅋ', 'ㅇ', 'ㅎ', 'ㅠ', 'ㄱ', 'ㄴ', "'", '"', '(', '[', '{', '…', '!', '?')


def rewrite_dot(text, who_key, nth):
    """말머리 "…" 를 걷어낸 글.

    줄 전체가 "…" 였으면 그 캐릭터의 한 줄로 바꾸고, 그 밖에는 문장을 그대로 세운다
    (대부분은 "…" 만 빠져도 문장이 산다). 세 번에 한 번,
    **문장 앞에 붙여도 말이 되는 경우에만** 그 캐릭터의 호흡을 한 마디 얹는다.
    """
    rest = strip_lead(text)
    if not rest:
        return DOT_ALONE.get(who_key, '…')
    pool = DOT_PREFIX.get(who_key)
    if not pool or nth % PREFIX_EVERY:
        return rest
    if rest.startswith(NO_PREFIX_HEAD) or len(rest) < 6:
        return rest
    # 호격("서연아?")이나 한 어절짜리 줄에는 붙이지 않는다.
    first = rest.split()[0]
    if first.endswith(('아?', '야?', '아.', '야.')) or len(rest.split()) < 2:
        return rest
    if len(first) <= 3 and first.rstrip('.?!').endswith(('네', '다', '지', '어', '음', '군')):
        return rest  # "…했네. 자라" 처럼 앞 줄에 이어지는 서술어 조각
    head = pool[(nth // PREFIX_EVERY) % len(pool)]
    if head.strip() in rest.split():
        return rest  # 같은 감탄사가 줄 안에 또 있으면 겹친다
    return head + rest


def is_wait(l):
    return line_who(l) == 'sys' and (0 if isinstance(l, str) else l.get('wait', 0)) > 0


def plan_dots(ev):
    """이 이벤트에서 살릴 "…" 와 지울 "…" 를 정한다. → (살릴 것, 지울 것) 경로 집합"""
    lines = ev.get('lines', [])
    lines_tail_wait = bool(lines) and is_wait(lines[-1])

    def dots_in(arr, name, first_after_wait):
        out = []
        for i, l in enumerate(arr):
            if line_who(l) != 'them' or not line_text(l).startswith(LEAD):
                continue
            prev_wait = is_wait(arr[i - 1]) if i > 0 else first_after_wait
            # 줄 전체가 "…" 인 것은 말머리가 아니라 **침묵 한 칸**이다. 그 자체가 연출이라
            # 예산에서 빼고 남긴다. 단 `wait` 바로 다음이면 침묵이 두 번이라 지운다.
            if line_text(l).strip() == LEAD and not prev_wait:
                continue
            out.append((f'{name}[{i}]', l, prev_wait))
        return out

    keep, drop = set(), set()

    def choose(cands, budget):
        """앞에서부터 budget 개만 살린다. `wait` 다음 줄과 예산 밖은 버린다."""
        got = 0
        # 침묵 한 칸("…" 뿐인 줄) → 짧은 줄("…나도", "…어") → 앞줄 차례로 살린다.
        # 짧을수록 "…" 가 문장이 아니라 호흡 그 자체라 지우면 장면이 빈다.
        order = sorted(range(len(cands)), key=lambda i: (
            line_text(cands[i][1]).strip() != LEAD,
            len(strip_lead(line_text(cands[i][1]))) > 8, i))
        picked = set()
        for i in order:
            path, l, after_wait = cands[i]
            if (ev['id'], path) in PROTECTED:
                picked.add(i)
                continue
            if after_wait or got >= budget:
                continue
            picked.add(i)
            got += 1
        for i, (path, l, _) in enumerate(cands):
            (keep if i in picked else drop).add(path)
        return got

    used = choose(dots_in(lines, 'L', False), 1)
    for ci, ch in enumerate(ev.get('choices', [])):
        for k in REPLY_KEYS:
            if k not in ch:
                continue
            arr = [ch[k]] if isinstance(ch[k], str) else ch[k]
            choose(dots_in(arr, f'C{ci}.{k}', lines_tail_wait), max(0, 1 - used))
    return keep, drop


