def line_text(l):
    return l if isinstance(l, str) else (l.get('text') or '')


def line_who(l):
    return 'them' if isinstance(l, str) else (l.get('who') or 'them')


def line_name(l):
    return None if isinstance(l, str) else l.get('name')


def set_line(l, text=None, who=None):
    """줄 하나를 고친 사본. 문자열 줄에 who 가 붙으면 객체로 바뀐다."""
    if isinstance(l, str):
        if who in (None, 'them'):
            return l if text is None else text
        return {'who': who, 'text': l if text is None else text}
    out = dict(l)
    if text is not None:
        out['text'] = text
    if who is not None:
        out['who'] = who
    return out


def iter_arrays(ev):
    """(경로, 목록 또는 None, 넣는 함수) — 문자열 반응도 한 줄짜리 목록처럼 본다."""
    yield 'L', ev.get('lines', []), lambda v: ev.__setitem__('lines', v)
    for ci, ch in enumerate(ev.get('choices', [])):
        for k in REPLY_KEYS:
            if k not in ch:
                continue
            v = ch[k]
            lst = [v] if isinstance(v, str) else v

            def put(new, ch=ch, k=k, was_str=isinstance(v, str)):
                if was_str and len(new) == 1 and isinstance(new[0], str):
                    ch[k] = new[0]
                else:
                    ch[k] = new
            yield f'C{ci}.{k}', lst, put


def _line_at(ev, path):
    """'C0.reply[1]' 같은 경로가 가리키는 (이름, 목록, 자리). 없으면 (None, None, None)."""
    for name, arr, _put in iter_arrays(ev):
        if not path.startswith(name + '['):
            continue
        i = int(path[len(name) + 1:-1])
        if i < len(arr):
            return name, arr, i
    return None, None, None


