#   1. 한 경로(= 이벤트의 `lines` + 고른 선택지의 반응 한 벌)에 "…" 로 시작하는
#      상대 줄은 최대 하나.
#   2. `wait` 바로 다음 줄에는 쓰지 않는다 — 카운트다운이 이미 침묵을 연출했다.
#   3. 캐릭터별 상한(그 캐릭터 상대 대사의 몇 %). 침묵이 캐릭터인 다은·정우만 높다.
