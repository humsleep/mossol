# 화자 이름이 비어 나오던 `them` 줄 앞에 상대를 밝히는 지문을 넣는다.
# `Line.name` 은 자리표시자를 치환하지 않으므로(models.dart:513 `name: name`) 지문으로 푼다.
PREPEND_LINES: dict[str, list[tuple[int, dict]]] = {
    "d_kakao_03": [(0, {"who": "narr", "text": "{top|과와} 하던 대화방이다."})],
}


def _apply(ev: dict, pairs: list[tuple[str, str]]) -> dict[str, int]:
    hits = {old: 0 for old, _ in pairs}

    def fix(s):
        for old, new in pairs:
            if s == old:
                hits[old] += 1
                return new
        return s

    for l in ev.get("lines") or []:
        if "text" in l:
            l["text"] = fix(l["text"])
    for c in ev.get("choices") or []:
        c["text"] = fix(c["text"])
        for k in ("reply", "failReply", "critReply"):
            for l in c.get(k) or []:
                if "text" in l:
                    l["text"] = fix(l["text"])
    for k in ("title", "cliffhanger", "preview"):
        if ev.get(k):
            ev[k] = fix(ev[k])
    return hits


def main() -> int:
    events = story_io.load("events_daily.json")
    index = story_io.by_id(events)
    missing, changed = [], 0

    for eid, pairs in REWRITES.items():
        ev = index.get(eid)
        if ev is None:
            missing.append(f"{eid}: 이벤트 없음")
            continue
        hits = _apply(ev, pairs)
        for old, n in hits.items():
            if n == 0:
                missing.append(f'{eid}: 못 찾음 "{old}"')
        changed += sum(hits.values())

    for eid, inserts in PREPEND_LINES.items():
        ev = index.get(eid)
        if ev is None:
            missing.append(f"{eid}: 이벤트 없음")
            continue
        for at, line in inserts:
            if ev["lines"][at] == line:
                continue
            ev["lines"].insert(at, dict(line))
            changed += 1

    if missing:
        print("멈춤 — 바꿀 대상을 못 찾았다(파일은 그대로 둔다):", file=sys.stderr)
        for m in missing:
            print("  " + m, file=sys.stderr)
        return 1

    story_io.save("events_daily.json", events)
    print(f"{len(REWRITES)}개 이벤트 · {changed}곳을 {{top}} 으로 고쳤다.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
