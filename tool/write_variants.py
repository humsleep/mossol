"""반복 가능한 일상 24개 전부에 변형 대사 2벌씩 붙인다 (12_engine_handoff.md §0.1).

100일 완주 회차에서 일상 칸은 약 152번 뽑는데 그 회차에 낼 수 있는 일상은 99종뿐이다.
차이 53번은 어떤 추첨 규칙으로도 못 지운다 — **그 53번을 누가 받느냐가 문제다.**
지금은 반복 가능한 24개가 전부 받아서, 한 장면을 회차당 4~5번 읽는다.

`StoryEvent.variants` 는 대사 묶음을 `(시드로 정한 시작점 + 본 횟수) % (N+1)` 로 돌린다.
원본 + 변형 2벌 = 3벌이면 **세 번째로 볼 때까지 글자가 안 겹친다.** 24개 전부에 붙였으므로
반복 풀 전체가 24종 → 실효 72종이 된다.

규칙(검증기가 막는 것):
  - `once: true` 에는 못 붙인다 → 여기서 손대는 건 반복 가능한 24개뿐이다.
  - 사진 줄 유무가 원본과 같아야 한다 → 24개 다 원본에 사진 줄이 없으므로 변형에도 없다.
  - 바뀌는 건 **대사뿐**이다. 선택지·효과·조건·미니게임·알림은 원본 그대로다.
    그래서 변형은 **같은 선택지 세 개로 이어지는 다른 도입부**여야 한다 —
    예컨대 `d_kakao_05` 의 세 번째 선택지가 "ㅋㅋ 아니고 ㅠㅠ 였어" 이므로
    변형 둘 다 'ㅋㅋ 오타를 보냈다'까지는 반드시 간다.

사용: python3 tool/write_variants.py [--dry]
"""

