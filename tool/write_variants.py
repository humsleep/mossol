DRY = "--dry" in sys.argv
daily = story_io.load("events_daily.json")
d = story_io.by_id(daily)

problems: list[str] = []
done = 0
for eid, sets in VARIANTS.items():
    ev = d.get(eid)
    if ev is None:
        problems.append(f"없는 id: {eid}")
        continue
    if ev.get("once", True):
        problems.append(f"{eid} 는 once:true 다 — 변형을 붙이면 검증기가 막는다")
        continue
    if "variants" in ev:
        problems.append(f"{eid} 에 이미 variants 가 있다")
        continue
    base_photo = any("photo" in l for l in ev["lines"])
    for i, s in enumerate(sets):
        if not s:
            problems.append(f"{eid} 변형[{i}] 이 비었다")
        if any("photo" in l for l in s) != base_photo:
            problems.append(f"{eid} 변형[{i}] 의 사진 줄 유무가 원본과 다르다")
    ev["variants"] = [{"lines": s} for s in sets]
    done += 1

if problems:
    print("멈춤 — 파일을 쓰지 않았다.")
    for p in problems:
        print("  !", p)
    raise SystemExit(1)

total = sum(len(v) for v in VARIANTS.values())
print(f"변형을 붙인 이벤트 {done}개 · 새로 쓴 대사 묶음 {total}벌")
