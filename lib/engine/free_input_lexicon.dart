/// 제한형 자유 입력의 의도 사전(docs/overhaul/07_free_input.md §1.3).
///
/// 전역 하나. 입력·선택지 문구·반응 줄 모두 같은 사전으로 태그를 뽑는다. 이벤트별 튜닝은 여기가 아니라
/// 선택지의 `intent` 필드로 한다 — 이벤트 하나 때문에 사전을 건드리지 않는다.
///
/// 항목 표기 규칙(`FreeInputLexicon.tags`):
/// - 기본은 **공백·문장부호를 뺀 문자열**에 대한 부분 문자열 검사다. "안 해" 는 `안해` 로 적는다.
/// - `^` 로 시작하면 **낱말 전체**(공백으로 나눈 토큰과 완전 일치)여야 한다. `응`·`어`·`네` 처럼
///   한 음절이라 아무 데나 걸리는 말에 쓴다(`어디`·`없어` 가 agree 가 되면 안 된다).
/// - `?` 로 끝나면 입력이 질문(`?` 또는 의문 어미)일 때만 걸린다(`괜찮아?` 는 care, `괜찮아요` 는 refuse).
/// - `!` 로 끝나면 질문이 **아닐** 때만 걸린다(`휴지 아니야?` 는 추측이지 거절이 아니다).
